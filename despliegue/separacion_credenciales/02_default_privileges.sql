-- =============================================================================
--  B.6  --  PASO 2: DEFAULT PRIVILEGES PARA crm_owner
-- =============================================================================
--
--    *** NO EJECUTAR EN PRODUCCION SIN AUTORIZACION EXPLICITA ***
--
--  VA ANTES DE LA TRANSFERENCIA (paso 3), no despues. Asi, cualquier tabla que
--  se cree entre medias ya nace con los permisos correctos y no queda un hueco
--  que alguien tenga que recordar tapar.
--
--  El problema que resuelve
--  ------------------------
--  Produccion tiene 'ALTER DEFAULT PRIVILEGES FOR ROLE postgres ... TO crm_user'
--  (verificado en B.2). Esos defaults se disparan por QUIEN CREA el objeto. En
--  cuanto quien cree pase a ser crm_owner, dejan de aplicar y crm_user se queda
--  SIN PERMISO sobre cada tabla nueva.
--
--  Medido en B.4: sin esta declaracion, una tabla recien creada por una
--  migracion da select=false / insert=false para crm_user. La migracion pasa en
--  verde y deja la aplicacion rota en la primera peticion real. Es la peor
--  forma de fallar.
--
--  Uso:
--    psql "$DSN" -v ON_ERROR_STOP=1 -f 02_default_privileges.sql
-- =============================================================================

\set ON_ERROR_STOP on

begin;

-- -----------------------------------------------------------------------------
--  Lo que recibe el TRAFICO sobre lo que cree el dueno
-- -----------------------------------------------------------------------------
--  Solo DML. Ni un permiso de estructura: el usuario de trafico no hace DDL, y
--  esa separacion es el objetivo entero de esta transicion.
alter default privileges for role crm_owner in schema public
  grant select, insert, update, delete on tables to crm_user;

--  La linea de secuencias NO es decorativa. Sin USAGE sobre la secuencia de una
--  columna 'identity', el primer INSERT falla al pedir el siguiente id -- y el
--  error no menciona la secuencia, asi que se busca en el sitio equivocado.
--  Las 51 secuencias de produccion son todas de columnas identity (medido en
--  B.3: attidentity='d', deptype='i').
alter default privileges for role crm_owner in schema public
  grant usage, select on sequences to crm_user;

--  Funciones: el CRM no define ninguna en 'public' (las 145 que hay son de
--  supabase_admin, verificado en B.3), pero si una migracion futura creara una,
--  el trafico necesitaria poder ejecutarla.
alter default privileges for role crm_owner in schema public
  grant execute on functions to crm_user;

-- -----------------------------------------------------------------------------
--  Lo que NO se toca
-- -----------------------------------------------------------------------------
--  Los defaults de 'for role postgres' se DEJAN COMO ESTAN. Siguen valiendo
--  para cualquier cosa que postgres cree en una emergencia, y quitarlos no
--  aporta nada salvo un camino menos de recuperacion.
--
--  Tampoco se declara nada para crm_migrator: no crea objetos como si mismo
--  -- arranca con 'set role = crm_owner' (paso 1), asi que todo lo que cree
--  cae bajo los defaults de arriba.

-- -----------------------------------------------------------------------------
--  COMPROBACION
-- -----------------------------------------------------------------------------
do $$
declare n int;
begin
  select count(*) into n
    from pg_default_acl d
    join pg_roles r on r.oid = d.defaclrole
    left join pg_namespace ns on ns.oid = d.defaclnamespace
   where r.rolname = 'crm_owner'
     and ns.nspname = 'public'
     and d.defaclacl::text like '%crm_user=%';

  if n < 2 then
    raise exception 'los DEFAULT PRIVILEGES de crm_owner no quedaron: % entrada(s) '
                    'mencionan a crm_user (se esperaban al menos 2: tablas y secuencias)', n;
  end if;
  raise notice 'OK: % entrada(s) de default privileges para crm_owner -> crm_user', n;
end $$;

commit;

